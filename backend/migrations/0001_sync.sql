CREATE TABLE IF NOT EXISTS head (id INTEGER PRIMARY KEY CHECK(id=1), version INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO head(id,version) VALUES(1,0);
CREATE TABLE IF NOT EXISTS versions (
 version INTEGER PRIMARY KEY, mutation_id TEXT NOT NULL UNIQUE, device_id TEXT NOT NULL,
 digest TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 tombstones TEXT NOT NULL, summary TEXT NOT NULL, backup_id TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS chunks (version INTEGER NOT NULL, part INTEGER NOT NULL, body TEXT NOT NULL, PRIMARY KEY(version,part), FOREIGN KEY(version) REFERENCES versions(version));
CREATE TABLE IF NOT EXISTS backups (id TEXT PRIMARY KEY, device_id TEXT NOT NULL, digest TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS backup_chunks (backup_id TEXT NOT NULL, part INTEGER NOT NULL, body TEXT NOT NULL, PRIMARY KEY(backup_id,part), FOREIGN KEY(backup_id) REFERENCES backups(id));
CREATE TABLE IF NOT EXISTS devices (id TEXT PRIMARY KEY, backup_id TEXT NOT NULL, migrated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS rate_limits (key TEXT PRIMARY KEY, window INTEGER NOT NULL, count INTEGER NOT NULL);
